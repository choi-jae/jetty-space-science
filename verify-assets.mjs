import {readFileSync,statSync} from 'node:fs';
import {isFree,moveWithCollisions} from './public/world-collision.js';
import assert from 'node:assert/strict';
const data=readFileSync(new URL('./public/models/jetty_boy.glb',import.meta.url));
assert.equal(data.toString('ascii',0,4),'glTF','GLB header');
assert.equal(data.readUInt32LE(4),2,'GLB version');
assert.equal(data.readUInt32LE(8),data.length,'GLB length');
assert.equal(data.toString('ascii',16,20),'JSON');
const json=JSON.parse(data.subarray(20,20+data.readUInt32LE(12)).toString('utf8'));
assert.deepEqual(['Idle','Walk','Wave'].every(name=>json.animations.some(a=>a.name===name)),true);
assert.equal(json.meshes.length,9);
assert.equal(isFree(0,7.2),true,'starting position');
assert.equal(isFree(-7,-12),false,'internal wall');
assert.equal(isFree(0,-4.65),true,'wave hall door');
const next=moveWithCollisions(-6,-12,-3,0);
assert.ok(next.x>-6.7,'wall collision should prevent crossing');
const srv=readFileSync(new URL('./server.js',import.meta.url),'utf8');
assert.ok(srv.includes("'.glb':'model/gltf-binary'"),'GLB MIME');
assert.ok(srv.includes("'/vendor/jsm/'"),'Three loader module mapping');
const ui=readFileSync(new URL('./public/index.html',import.meta.url),'utf8');
assert.ok(ui.includes('id="avatarStatus"'),'visible load status');
console.log(`PASS: GLB ${(statSync(new URL('./public/models/jetty_boy.glb',import.meta.url)).size/1024).toFixed(0)} KB, ${json.meshes.length} meshes, ${json.animations.map(a=>a.name).join('/')}, collision tests, vendor paths`);
